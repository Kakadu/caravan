(* Shared context and helpers for the dune build emitter.
 *
 * Written in Base (not Core) per the Core -> Base migration plan.
 *)
open Base

type t = {
  root : string;
  (** Repository root (absolute path). *)
  out_dir : string;
  (** Output directory standing in for [build/base/gen]. *)
  build : Model.build;
  (** The inferred build model. *)
}

(** Banner of generated files. The legacy build stamps the host GNU Make
 *  version here; the oracle was produced with 4.4.1. *)
let banner = "Generated by GNU Make 4.4.1. Do not edit."

let kind_string = function
  | Model.String -> "STRING"
  | Model.Number -> "NUMBER"
  | Model.Boolean -> "BOOLEAN"
  | Model.TypeRef -> "TYPEREF"

let container_fqn (opt : Model.option_def) : Model.fqn =
  match opt.opt_container with
  | C_module mt -> mt.mt_fqn
  | C_annotation at -> at.at_fqn

(** [option_id opt] is the C macro id of [opt], mirroring the legacy
 *  [Option.getId]: [OPTION_<KIND>_<containerFqn as __id>_<name>]. *)
let option_id (opt : Model.option_def) =
  "OPTION_" ^ kind_string opt.opt_kind ^ "_"
    ^ Model.fqn_to_id (container_fqn opt @ [ opt.opt_name ])

(** [inherited_option_id opt t] is the id of [opt] as seen from type [t]:
 *  the container part of the id is replaced by [t]'s fqn (legacy
 *  [__inherited_option_id]). *)
let inherited_option_id (opt : Model.option_def) (t : Model.module_type) =
  "OPTION_" ^ kind_string opt.opt_kind ^ "_"
    ^ Model.fqn_to_id (t.mt_fqn @ [ opt.opt_name ])

(** Render a bound value the way the legacy [Value.toString] does:
 *  strings raw (unquoted), booleans as 0/1, type references by qualified
 *  name. Numbers: the legacy preserves decimal literals verbatim (so
 *  [0022] keeps its leading zeros) but normalises hex literals to decimal
 *  ([0xf0040000] becomes [4026793984]). *)
let render_value (v : Model.value) =
  match v with
  | V_string s -> s
  | V_number { lexeme; value; _ } ->
      let is_hex =
        String.is_prefix ~prefix:"0x" lexeme
        || String.is_prefix ~prefix:"-0x" lexeme
      in
      if is_hex then
        if Float.equal value (Stdlib.floor value)
        then Int.to_string (Int.of_float value)
        else Float.to_string value
      else lexeme
  | V_bool b -> if b then "1" else "0"
  | V_ref r -> Model.fqn_to_string r
  | V_module mt -> Model.fqn_to_string mt.mt_fqn

(** Every module type that participates in the build (each instance type
 *  and all of its super types) paired with the instance that owns it.
 *  Mirrors the legacy [moduleInstanceByName] store, which is keyed by the
 *  qualified name of the instance type and of all its super types. *)
let header_targets (b : Model.build) : (Model.module_type * Model.module_instance) list =
  let h = Hashtbl.create (module String) in
  List.iter b.bd_modules ~f:(fun inst ->
    let t = inst.mi_type in
    List.iter ([ t ] @ t.mt_all_super) ~f:(fun s ->
      Hashtbl.set h ~key:(Model.fqn_to_string s.mt_fqn) ~data:(s, inst)));
  List.map (Hashtbl.to_alist h) ~f:(fun (_, v) -> v)

