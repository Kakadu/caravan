(** Canonical annotation type fqns used by the C runtime injection. *)
let ann_cmd = [ "mybuild"; "lang"; "Cmd" ]
let ann_cxx_cmd = [ "mybuild"; "lang"; "CxxCmd" ]
let ann_app = [ "mybuild"; "lang"; "App" ]
let ann_runlevel = [ "mybuild"; "lang"; "Runlevel" ]
let ann_linker_section = [ "mybuild"; "lang"; "LinkerSection" ]

let fqn_eq = Model.fqn_equal

(** [all_types inst] = the instance's type and all its super types,
 *  nearest first (legacy [allTypes]). *)
let all_types (inst : Model.module_instance) : Model.module_type list =
  let t = inst.mi_type in
  [ t ] @ t.mt_all_super

(** True if any of [inst]'s types carries an annotation of type [fqn]
 *  (legacy [is_a]). *)
let has_ann_on_all_types (inst : Model.module_instance) (fqn : Model.fqn) : bool =
  List.exists (all_types inst) ~f:(fun mt ->
    List.exists mt.mt_annotations ~f:(fun a -> fqn_eq a.ann_type.at_fqn fqn))

(** The value of the [param] parameter of the [fqn] annotation in the
 *  annotation list [anns]. A single-value annotation (e.g. [@Runlevel(1)])
 *  is bound to the annotation type's first option, mirroring the legacy. *)
let anns_param (anns : Model.annotation list) (fqn : Model.fqn) (param : string) :
    Model.value option =
  List.find_map anns ~f:(fun a ->
    if not (fqn_eq a.ann_type.at_fqn fqn) then None
    else
      match a.ann_arg with
      | Some (Ann_params ps) ->
          List.find_map ps ~f:(fun (n, v) ->
            if String.equal n param then Some v else None)
      | Some (Ann_value v) ->
          (match a.ann_type.at_options with
           | o :: _ when String.equal o.opt_name param -> Some v
           | _ -> None)
      | None -> None)

(** The value of the [param] parameter of the [fqn] annotation on the
 *  instance's own type (legacy [module_annotation_value], which reads
 *  [get(m, type)] -- the most specific type only). *)
let ann_param (inst : Model.module_instance) (fqn : Model.fqn) (param : string) :
    Model.value option =
  anns_param inst.mi_type.mt_annotations fqn param

(** The value of the [param] parameter of the [fqn] annotation on module
 *  type [mt] (type-level analogue of [ann_param]). *)
let type_ann_param (mt : Model.module_type) (fqn : Model.fqn) (param : string) :
    Model.value option =
  List.find_map mt.mt_annotations ~f:(fun a ->
    if not (fqn_eq a.ann_type.at_fqn fqn) then None
    else
      match a.ann_arg with
      | Some (Ann_params ps) ->
          List.find_map ps ~f:(fun (n, v) ->
            if String.equal n param then Some v else None)
      | _ -> None)

(** The value of the option named [name] bound on [inst] (bound value or
 *  default), rendered the way the legacy [Value.toString] does. Returns
 *  [None] when the option is not bound (legacy [getOptionValueStringByName]
 *  yields empty). *)
let option_value_string (inst : Model.module_instance) (name : string) : string option =
  List.find_map inst.mi_options ~f:(fun oi ->
    if String.equal oi.oi_option.opt_name name then Some (render_value oi.oi_value)
    else None)

(** Runtime dependencies of [inst]: [mi_depends] minus
 *  [mi_no_runtime_depends] (legacy [mod_inst_get_deps ... depends]). The
 *  legacy stores [depends] as a set (via [set*]), so duplicates are
 *  dropped keeping the first occurrence. *)
let runtime_deps (inst : Model.module_instance) : Model.module_instance list =
  let nr_fqns = List.map inst.mi_no_runtime_depends ~f:(fun d -> d.mi_type.mt_fqn) in
  let seen = ref [] in
  List.filter inst.mi_depends ~f:(fun d ->
    let fqn = d.mi_type.mt_fqn in
    if List.mem nr_fqns fqn ~equal:Model.fqn_equal then false
    else if List.mem !seen fqn ~equal:Model.fqn_equal then false
    else (
      seen := fqn :: !seen;
      true))

(** [str_escape s] mirrors the legacy [str_escape] make function: the
 *  result is a double-quoted C string literal where backslashes, quotes,
 *  tabs and newlines are escaped; newlines split the literal into
 *  consecutive quoted pieces joined by a newline and a tab. *)
let str_escape (s : string) : string =
  let buf = Buffer.create 64 in
  String.iter s ~f:(function
    | '\\' -> Buffer.add_string buf "\\\\"
    | '"' -> Buffer.add_string buf "\\\""
    | '\t' -> Buffer.add_string buf "\\t"
    | '\n' -> Buffer.add_string buf "\\n\"\n\t\""
    | c -> Buffer.add_char buf c);
  "\"" ^ Buffer.contents buf ^ "\""

(** True when [needle] occurs in [hay] (a plain substring search; Base's
 *  [String.contains] only tests a single character). *)
let contains (hay : string) (needle : string) : bool =
  let hl = String.length hay in
  let nl = String.length needle in
  if nl > hl then false
  else
    let rec loop i =
      if i + nl > hl then false
      else if String.equal (String.sub hay ~pos:i ~len:nl) needle then true
      else loop (i + 1)
    in
    loop 0
